// withCleanedView gives a note a cleaned view as the worker would have left
// it, so a body write has something to mark stale.
func (h *editHarness) withCleanedView(userID string, n model.NoteIndex, autoClean bool, mode model.NoteCleanMode) model.NoteIndex {
	h.t.Helper()
	stored, err := h.store.GetNote(h.ctx, userID, n.ID)
	if err != nil {
		h.t.Fatalf("GetNote: %v", err)
	}
	stored.CleanedBody = "# Cleaned\n\nThe view."
	stored.CleanedMode = model.NoteCleanStructured
	stored.CleanedAt = model.Now()
	stored.CleanedStale = false
	stored.AutoClean = autoClean
	stored.CleanMode = mode
	updated, err := h.store.PutNote(h.ctx, userID, stored)
	if err != nil {
		h.t.Fatalf("PutNote: %v", err)
	}
	return updated
}

func (h *editHarness) get(userID, noteID string) model.NoteIndex {
	h.t.Helper()
	n, err := h.store.GetNote(h.ctx, userID, noteID)
	if err != nil {
		h.t.Fatalf("GetNote: %v", err)
	}
	return n
}

// Every body write marks an existing view stale; nothing else does.
func TestEditingTheBodyMarksTheCleanedViewStale(t *testing.T) {
	h := newEditHarness(t)
	n := h.withCleanedView("u", h.note("u", "Roof", "the gutter leaks"), false, "")

	version := n.Version
	title := "Roof repair"
	updated, err := h.notes.UpdateNote(h.ctx, "u", n.ID, NoteUpdates{Title: &title, ExpectedVersion: &version})
	if err != nil {
		t.Fatalf("UpdateNote(title): %v", err)
	}
	if updated.CleanedStale {
		t.Error("a title edit marked the view stale; only the body feeds the view")
	}
	if updated.CleanedBody == "" {
		t.Error("a title edit lost the cleaned body")
	}

	version = updated.Version
	body := "the gutter leaks badly"
	updated, err = h.notes.UpdateNote(h.ctx, "u", n.ID, NoteUpdates{Body: &body, ExpectedVersion: &version})
	if err != nil {
		t.Fatalf("UpdateNote(body): %v", err)
	}
	if !updated.CleanedStale {
		t.Error("a body edit did not mark the view stale")
	}
	if updated.CleanedBody != "# Cleaned\n\nThe view." {
		t.Errorf("a body edit changed the cleaned body itself: %q; the view is read-only and regenerated by the worker", updated.CleanedBody)
	}
}

